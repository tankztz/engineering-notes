import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const dist = new URL('../docs/.vitepress/dist/', import.meta.url)
let template = readFileSync(new URL('index.html', dist), 'utf8')
// Keep VitePress bootstrap scripts compatible with script-src 'self'; no inline execution.
template = template.replace(/<script\b([^>]*)>([\s\S]*?)<\/script>/g, (tag, attributes, script) => {
  if (/\bsrc=/.test(attributes) || !script.trim()) return tag
  const name = `assets/bootstrap.${createHash('sha256').update(script).digest('hex').slice(0, 16)}.js`
  writeFileSync(new URL(name, dist), script)
  return `<script${attributes} src="/${name}"></script>`
})
writeFileSync(new URL('index.html', dist), template)
writeFileSync(new URL('../src/generated-template.ts', import.meta.url), `// Generated by npm run docs:build. Contains no lesson data.\nexport default ${JSON.stringify(template)}\n`)
